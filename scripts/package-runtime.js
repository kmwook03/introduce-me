import { build } from 'esbuild';
import { readFile, readdir, writeFile } from 'node:fs/promises';
import { gzipSync } from 'node:zlib';
import { createHash } from 'node:crypto';
import { fileURLToPath } from 'node:url';
import path from 'node:path';

const root = fileURLToPath(new URL('../', import.meta.url));
const check = process.argv.includes('--check');
const bundle = await build({
  absWorkingDir: root,
  entryPoints: ['src/server.js'],
  bundle: true,
  write: false,
  platform: 'node',
  target: 'node24',
  format: 'esm',
  minify: true,
  // pg-native is an optional pg accessor; the application uses the bundled JS driver.
  external: ['pg-native'],
  banner: { js: 'import { createRequire as __createRequire } from "node:module"; const require = __createRequire(import.meta.url);' },
});
const files = { 'src/server.mjs': Buffer.from(bundle.outputFiles[0].contents).toString('base64') };
async function addDirectory(directory) {
  for (const entry of (await readdir(path.join(root, directory), { withFileTypes: true })).sort((a, b) => a.name < b.name ? -1 : 1)) {
    const relative = `${directory}/${entry.name}`;
    if (entry.isDirectory()) await addDirectory(relative);
    else if (entry.isFile()) files[relative] = (await readFile(path.join(root, relative))).toString('base64');
    else throw new Error('Only regular files can be packaged');
  }
}
await addDirectory('public');
await addDirectory('migrations');
const archive = gzipSync(JSON.stringify(files), { level: 9 });
// Kubernetes limits the decoded ConfigMap content to 1 MiB. Keep headroom for metadata.
if (archive.length > 900 * 1024) throw new Error('Runtime payload exceeds the safe ConfigMap size; use a prebuilt service image');
const checksum = createHash('sha256').update(archive).digest('hex');
// oc apply stores the entire manifest in a last-applied annotation (256 KiB limit).
// Split into 128 KiB decoded parts so even client-side oc apply works without flags.
const manifests = [];
for (let offset = 0; offset < archive.length; offset += 128 * 1024) {
  const index = String(manifests.length).padStart(2, '0');
  manifests.push({
    apiVersion: 'v1', kind: 'ConfigMap',
    metadata: { name: `personal-portfolio-runtime-${index}`, labels: { app: 'personal-portfolio' }, annotations: { 'portfolio/runtime-sha256': checksum } },
    binaryData: { [`runtime-${index}.part`]: archive.subarray(offset, offset + 128 * 1024).toString('base64') },
  });
}
const generated = '# Generated by npm run deploy:generate. JSON is valid YAML. Do not edit.\n' + manifests.map(manifest => JSON.stringify(manifest, null, 2)).join('\n---\n') + '\n';
const target = path.join(root, 'deploy/k8s/runtime-configmap.yaml');
const deploymentPath = path.join(root, 'deploy/k8s/web-deployment.yaml');
const deployment = await readFile(deploymentPath, 'utf8');
const sources = manifests.map(manifest => `              - configMap:\n                  name: ${manifest.metadata.name}`).join('\n');
const updated = deployment.replace(/portfolio\/runtime-sha256: "[^"]*"/, `portfolio/runtime-sha256: "${checksum}"`)
  .replace(/(# BEGIN RUNTIME SOURCES\n)[\s\S]*?(\s*# END RUNTIME SOURCES)/, `$1${sources}\n            # END RUNTIME SOURCES`);
if (updated === deployment && !deployment.includes(checksum)) throw new Error('Deployment is missing the runtime checksum marker');
if (check) {
  if (await readFile(target, 'utf8') !== generated || updated !== deployment) throw new Error('Runtime is stale. Run npm run deploy:generate');
} else {
  await writeFile(target, generated);
  await writeFile(deploymentPath, updated);
}
console.info(`${check ? 'Verified' : 'Packaged'} ${Object.keys(files).length} files, ${archive.length} compressed bytes in ${manifests.length} ConfigMaps, sha256:${checksum}`);
